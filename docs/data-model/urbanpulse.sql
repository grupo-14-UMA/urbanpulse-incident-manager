CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE "User" (
  "id" integer PRIMARY KEY,
  "nif" varchar,
  "name" varchar(100) NOT NULL,
  "email" varchar(254) NOT NULL UNIQUE,
  "password_hash" varchar(60) NOT NULL,
  "phone" integer,
  "role_id" integer NOT NULL
);

CREATE TABLE "Role" (
  "id" integer PRIMARY KEY,
  "name" varchar
);

CREATE TABLE "UrbanAsset" (
  "id" integer PRIMARY KEY,
  "name" varchar,
  "asset_type_id" integer,
  "coordinates_id" integer,
  "geojson" JSONB
);

CREATE TABLE "AssetType" (
  "id" integer PRIMARY KEY,
  "name" varchar
);

CREATE TABLE "UrbanContext" (
  "id" integer PRIMARY KEY,
  "type_context_id" integer,
  "source" varchar,
  "json" JSONB,
  "observed_at" timestamptz
);

CREATE TABLE "ContextType" (
  "id" integer PRIMARY KEY,
  "name" varchar
);

CREATE TABLE "Category" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(100) NOT NULL UNIQUE
);

CREATE TABLE "Incident" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "title" varchar(255) NOT NULL,
  "description" varchar,
  "category_id" integer,
  "location" geometry(Point, 4326) NOT NULL,
  "priority" varchar(10),
  "priority_justification" varchar(1000),
  "status_id" integer NOT NULL,
  "assignee_id" integer,
  "version" integer NOT NULL DEFAULT 0,
  "reporter_id" integer,
  "urban_asset_id" integer,
  "urban_context_id" integer,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL
);

COMMENT ON COLUMN "Incident"."status_id" IS
  'References Status.';

COMMENT ON COLUMN "Incident"."priority" IS
  'LOW, MEDIUM, HIGH or URGENT. Null means no priority.';

COMMENT ON COLUMN "Incident"."assignee_id" IS
  'Technician in charge. Null until assigned.';

CREATE TABLE "Status" (
  "id" integer PRIMARY KEY,
  "name" varchar(20) NOT NULL UNIQUE
);

CREATE TABLE "Attachment" (
  "id" integer PRIMARY KEY,
  "incident_id" integer,
  "file_url" varchar,
  "file_type" varchar,
  "created_at" timestamptz
);

CREATE TABLE "FileType" (
  "id" integer PRIMARY KEY,
  "extension" varchar
);

CREATE TABLE "Assignment" (
  "id" integer PRIMARY KEY,
  "incident_id" integer,
  "assigned_user_id" integer,
  "department_id" varchar,
  "team_id" varchar,
  "assigned_at" timestamptz
);

CREATE TABLE "Team" (
  "id" integer PRIMARY KEY,
  "name" varchar,
  "department_id" integer,
  "member_user_id" integer
);

CREATE TABLE "Department" (
  "id" integer PRIMARY KEY,
  "name" varchar,
  "team_id" integer
);

CREATE TABLE "StatusChange" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "incident_id" integer NOT NULL,
  "previous_status_id" integer,
  "new_status_id" integer NOT NULL,
  "changed_by_id" integer,
  "changed_at" timestamptz NOT NULL,
  "note" varchar(1000)
);

CREATE TABLE "ExternalObservation" (
  "id" integer PRIMARY KEY,
  "incident_id" integer,
  "observed_at" timestamptz,
  "ingested_at" timestamptz,
  "unit" varchar,
  "quality" varchar
);

CREATE TABLE "Notification" (
  "id" integer PRIMARY KEY,
  "user_id" integer,
  "incident_id" integer,
  "description" varchar,
  "sent_at" timestamptz
);

CREATE TABLE "KnowledgeDocument" (
  "id" integer PRIMARY KEY,
  "title" varchar,
  "content" text,
  "version" varchar,
  "created_at" timestamptz
);


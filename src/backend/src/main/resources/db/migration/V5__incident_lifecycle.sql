CREATE TABLE "Status" (
    "id" integer PRIMARY KEY,
    "name" varchar(20) NOT NULL UNIQUE
);

INSERT INTO "Status" ("id", "name") VALUES
    (1, 'REPORTED'),
    (2, 'VALIDATED'),
    (3, 'REJECTED'),
    (4, 'ASSIGNED'),
    (5, 'IN_PROGRESS'),
    (6, 'RESOLVED');

ALTER TABLE "Incident"
    ADD CONSTRAINT "fk_incident_status"
        FOREIGN KEY ("status_id") REFERENCES "Status" ("id"),
    ADD COLUMN "priority" varchar(10)
        CHECK ("priority" IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    ADD COLUMN "priority_justification" varchar(1000),
    ADD COLUMN "assignee_id" integer,
    ADD COLUMN "version" integer NOT NULL DEFAULT 0,
    ADD CONSTRAINT "fk_incident_assignee"
        FOREIGN KEY ("assignee_id") REFERENCES "User" ("id");

COMMENT ON COLUMN "Incident"."status_id" IS
    'References Status.';
COMMENT ON COLUMN "Incident"."priority" IS
    'Manual priority set by an operator. Null means no priority.';
COMMENT ON COLUMN "Incident"."assignee_id" IS
    'Technician in charge of the incident. Null until it is assigned.';
COMMENT ON COLUMN "Incident"."version" IS
    'Optimistic locking counter, incremented by every change.';

CREATE TABLE "StatusChange" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "incident_id" integer NOT NULL,
    "previous_status_id" integer,
    "new_status_id" integer NOT NULL,
    "changed_by_id" integer,
    "changed_at" timestamptz NOT NULL DEFAULT now(),
    "note" varchar(1000),
    CONSTRAINT "fk_status_change_incident"
        FOREIGN KEY ("incident_id") REFERENCES "Incident" ("id"),
    CONSTRAINT "fk_status_change_previous_status"
        FOREIGN KEY ("previous_status_id") REFERENCES "Status" ("id"),
    CONSTRAINT "fk_status_change_new_status"
        FOREIGN KEY ("new_status_id") REFERENCES "Status" ("id"),
    CONSTRAINT "fk_status_change_changed_by"
        FOREIGN KEY ("changed_by_id") REFERENCES "User" ("id")
);

COMMENT ON COLUMN "StatusChange"."previous_status_id" IS
    'Null only for the initial entry of an incident.';
COMMENT ON COLUMN "StatusChange"."changed_by_id" IS
    'Null only for incidents stored before authentication, which have no reporter.';
COMMENT ON COLUMN "StatusChange"."note" IS
    'Rejection reason or resolution note.';

-- Supports reading the history of one incident in order.
CREATE INDEX "idx_status_change_incident_id_changed_at"
    ON "StatusChange" ("incident_id", "changed_at");

